data class AzExerciseEntry(
    val item: ExerciseItem,
    val muscleZone: MuscleGroupZone,
    val dbFolderId: String,
    val environment: ExerciseEnv = ExerciseEnv.BOTH,
    val isYouthSafe: Boolean = true
)

internal fun az(
    id: String,
    name: String,
    nameTr: String,
    targetMuscle: String,
    targetMuscleTr: String,
    secondaryMuscles: String,
    secondaryMusclesTr: String,
    muscleZone: MuscleGroupZone,
    dbFolderId: String,
    demoType: ExerciseDemoType,
    setsReps: String,
    restSeconds: Int,
    environment: ExerciseEnv,
    isYouthSafe: Boolean,
    step1: String,
    step2: String,
    step1Tr: String,
    step2Tr: String,
    formCue: String,
    formCueTr: String,
    breathingCue: String,
    breathingCueTr: String,
    commonMistake: String,
    commonMistakeTr: String,
    targetGroup: TargetGroup = TargetGroup.BOTH
): AzExerciseEntry = AzExerciseEntry(
    item = ExerciseItem(
        id = id,
        name = name,
        targetMuscle = targetMuscle,
        setsReps = setsReps,
        restSeconds = restSeconds,
        demoType = demoType,
        steps = listOf(step1, step2),
        formCue = formCue,
        breathingCue = breathingCue,
        commonMistake = commonMistake,
        targetGroup = targetGroup,
        secondaryMuscles = secondaryMuscles,
        nameTr = nameTr,
        targetMuscleTr = targetMuscleTr,
        secondaryMusclesTr = secondaryMusclesTr,
        stepsTr = listOf(step1Tr, step2Tr),
        formCueTr = formCueTr,
        breathingCueTr = breathingCueTr,
        commonMistakeTr = commonMistakeTr
    ),
    muscleZone = muscleZone,
    dbFolderId = dbFolderId,
    environment = environment,
    isYouthSafe = isYouthSafe
)


        (ExerciseDatabasePartAtoL.entries + ExerciseDatabasePartMtoZ.entries)
            .sortedBy { it.item.name.uppercase() }

    private val byIdMap: Map<String, AzExerciseEntry> =
        ALL_EXERCISES.associateBy { it.item.id }

    fun findById(id: String): AzExerciseEntry? = byIdMap[id]

    fun search(query: String, zoneFilter: MuscleGroupZone? = null): List<AzExerciseEntry> {
        val cleanQuery = query.trim().lowercase()
        return ALL_EXERCISES.filter { entry ->
            val zoneMatch = zoneFilter == null || entry.muscleZone == zoneFilter
            val textMatch = if (cleanQuery.isEmpty()) {
                true
            } else {
                entry.item.name.lowercase().contains(cleanQuery) ||
                    entry.item.nameTr.lowercase().contains(cleanQuery) ||
                    entry.item.targetMuscle.lowercase().contains(cleanQuery) ||
                    entry.item.targetMuscleTr.lowercase().contains(cleanQuery) ||
                    entry.item.secondaryMuscles.lowercase().contains(cleanQuery)
            }
            zoneMatch && textMatch
        }
    }
}
